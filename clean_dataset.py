# Load the listings data (sale or rent)
df_listings = pd.read_excel('sale_listings/sale_listings_32827.xlsx')
print("Listings:")
display(df_listings.head())

df_listings.head()
df_listings.info()
df_listings.isnull().mean().sort_values(ascending=False)

columns_to_drop = [
    'builder', 'history', 'listingAgent', 'listingOffice',
    'mlsName', 'mlsNumber', 'listingType', 'hoa',  # very sparse
    'createdDate', 'lastSeenDate', 'removedDate',  # redundant date info
]
df_listings = df_listings.drop(columns=columns_to_drop)

df_listings.columns = df_listings.columns.str.strip().str.lower().str.replace(" ", "_")

df_listings = df_listings.dropna(subset=[
    'latitude', 'longitude', 'bedrooms', 'bathrooms', 'squarefootage', 'price'
])

import re

def fix_lat(val):
    """Return float latitude ≈ 24–31 for Florida, else np.nan."""
    if pd.isna(val):
        return np.nan
    val = str(val).strip()
    # If it already parses to a reasonable float, keep it
    try:
        f = float(val)
        if 24 <= f <= 31:    # normal FL lat
            return f
    except ValueError:
        pass
    # Remove any non‑digit except dot, then rebuild
    digits = re.sub(r'[^\d]', '', val)
    if len(digits) < 3:
        return np.nan
    # Insert decimal after first 2 digits → 28.xxxxx
    rebuilt = float(digits[:2] + '.' + digits[2:])
    return rebuilt if 24 <= rebuilt <= 31 else np.nan

def fix_lon(val):
    """Return float longitude ≈ −90 to −70 (FL ≈ −81)."""
    if pd.isna(val):
        return np.nan
    val = str(val).strip()
    # Standard parse?
    try:
        f = float(val)
        if -90 <= f <= -70:
            return f
    except ValueError:
        pass
    # Remove non‑digits
    digits = re.sub(r'[^\d]', '', val)
    if len(digits) < 4:
        return np.nan
    # First 2 digits are 81, insert decimal after them, then negate
    rebuilt = -float(digits[:2] + '.' + digits[2:])
    return rebuilt if -90 <= rebuilt <= -70 else np.nan

# Apply
df_listings['latitude']  = df_listings['latitude'].apply(fix_lat)
df_listings['longitude'] = df_listings['longitude'].apply(fix_lon)

# Sanity ranges
print("Lat range:", df_listings['latitude'].min(), '-', df_listings['latitude'].max())
print("Lon range:", df_listings['longitude'].min(), '-', df_listings['longitude'].max())

def clean_bath(cell):
    """Return float bathrooms or np.nan"""
    if pd.isna(cell):
        return np.nan
    cell = str(cell).lower().strip()
    # remove spaces, tabs, commas
    cell = re.sub(r'[^0-9\.]', '', cell)
    # accept only patterns like 1, 1.5, 6.0
    if re.fullmatch(r'\d+(\.\d+)?', cell):
        val = float(cell)
        # sanity cap: nobody has >7 bathrooms in a single listing
        return val if val <= 7 else np.nan
    return np.nan

df_listings['bathrooms'] = df_listings['bathrooms'].apply(clean_bath)

# Optional median imputation for any remaining NaN
df_listings['bathrooms'] = (
    df_listings.groupby(['zipcode', 'bedrooms'])['bathrooms']
               .transform(lambda x: x.fillna(x.median()))
)

# Bathrooms range
print("Bath range:", df_listings['bathrooms'].min(), '–', df_listings['bathrooms'].max())

# Lat/Lon range (Orlando ≈ 28.3 / ‑81.4)
print("Lat range:", df_listings['latitude'].min(), '–', df_listings['latitude'].max())
print("Lon range:", df_listings['longitude'].min(), '–', df_listings['longitude'].max())

# Visual spot‑check
print(df_listings[['formattedaddress', 'bedrooms', 'bathrooms', 'latitude', 'longitude']].sample(5))

# Fill yearbuilt and lotsize using median per zip
df_listings['yearbuilt'] = df_listings.groupby('zipcode')['yearbuilt'].transform(lambda x: x.fillna(x.median()))
df_listings['lotsize'] = df_listings.groupby('zipcode')['lotsize'].transform(lambda x: x.fillna(x.median()))

# Make property type uniform
df_listings['propertytype'] = df_listings['propertytype'].str.lower().str.strip().str.replace(" ", "_")

# Create log-price for modeling

df_listings['log_price'] = np.log1p(df_listings['price'])

# Final check
print(df_listings.info())
print(df_listings.isnull().mean().sort_values(ascending=False).head(10))

# Save cleaned dataset
df_listings.to_csv("Data/Clean/clean_listings_32827.csv", index=False)



